/**
 * ERA token build.
 *
 * Reads the three collection dumps exported from the ERA Figma library and
 * emits:
 *   era.css     CSS custom properties, layered the same way the Figma
 *               collections are layered (primitives -> brand -> semantics)
 *   tokens.json W3C design-token format, for anyone who wants to pipe ERA
 *               into Style Dictionary or another transform
 *
 * The layering is the whole point. Primitives are raw values and never change.
 * Brand tokens re-point at primitives per brand. Semantic tokens re-point at
 * brand tokens per mode. Components only ever read semantic tokens, so a brand
 * swap is a single attribute change on <html> and nothing downstream moves.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'src');
const OUT = join(HERE, 'generated');
mkdirSync(OUT, { recursive: true });

const BRANDS = ['brand-1', 'brand-2', 'brand-3'];
const MODES = ['light', 'dark'];

const FONT_STACK = ', ui-sans-serif, system-ui, -apple-system, sans-serif';
const WEIGHTS = { Thin: 100, ExtraLight: 200, Light: 300, Regular: 400, Medium: 500, SemiBold: 600, Bold: 700, ExtraBold: 800, Black: 900 };

const read = (f) =>
  readFileSync(join(SRC, f), 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => l.split('|'));

/** `@P:x` / `P:x` -> `var(--x)`, `@B:x` -> `var(--brand-x)`, `@S:x` -> `var(--sem-x)` */
const PREFIX = { P: '', B: 'brand-', S: 'sem-' };
function refToVar(raw) {
  const m = /^@?([PBS]):(.+)$/.exec(raw);
  if (!m) return null;
  return `var(--${PREFIX[m[1]]}${m[2]})`;
}

/** Unitless by nature: grid column counts are a quantity, not a length. */
const isUnitless = (name) => /-columns$/.test(name);

function cssValue(name, type, raw) {
  const ref = refToVar(raw);
  if (ref) return ref;
  if (type === 'F') return isUnitless(name) ? raw : `${raw}px`;
  if (type === 'S') {
    if (/font-family/.test(name)) return `"${raw}"${FONT_STACK}`;
    if (/font-weight/.test(name)) return String(WEIGHTS[raw] ?? raw);
    return raw;
  }
  return raw; // colours are already hex / rgba()
}

// ---------------------------------------------------------------- primitives
const primitives = read('src-primitives.txt'); // name | type | value
const primCss = primitives.map(([n, t, v]) => `  --${n}: ${cssValue(n, t, v)};`);

// --------------------------------------------------------------------- brand
const brand = read('src-brand.txt'); // name | type | b1 | b2 | b3
const brandCss = BRANDS.map((_, i) =>
  brand.map(([n, t, ...vals]) => `  --brand-${n}: ${cssValue(n, t, vals[i])};`)
);

// ----------------------------------------------------------------- semantics
/**
 * Semantics are stored as `name | lightRef [| darkRef]`. When the dark ref is
 * omitted it is derived by inserting `-dark` after the family segment, which is
 * exactly how the dark ramps are named in the Brand collection. Overrides are
 * written out explicitly wherever dark deliberately diverges (surfaces,
 * alpha overlays, and the solid status fills that need a lighter step on dark).
 */
function deriveDark(ref) {
  const m = /^@?([PBS]):(.+)$/.exec(ref);
  if (!m) throw new Error(`unparseable semantic ref: ${ref}`);
  if (m[1] !== 'B') throw new Error(`cannot derive a dark counterpart for ${ref}; write it out explicitly`);
  const [family, ...rest] = m[2].split('-');
  return `B:${[family, 'dark', ...rest].join('-')}`;
}

const semantics = read('src-semantics.txt').map(([n, light, dark]) => [n, light, dark ?? deriveDark(light)]);
const semCss = MODES.map((_, i) =>
  semantics.map(([n, ...vals]) => `  --sem-${n}: ${cssValue(n, 'C', vals[i])};`)
);

// -------------------------------------------------------------------- verify
const defined = new Set([
  ...primitives.map(([n]) => `--${n}`),
  ...brand.map(([n]) => `--brand-${n}`),
  ...semantics.map(([n]) => `--sem-${n}`),
]);
const dangling = [];
for (const block of [primCss, ...brandCss, ...semCss].flat())
  for (const [, v] of block.matchAll(/var\((--[a-z0-9-]+)\)/g))
    if (!defined.has(v)) dangling.push(`${block.trim()}  ->  ${v}`);
if (dangling.length) {
  console.error('Dangling references:\n' + dangling.join('\n'));
  process.exit(1);
}

// ----------------------------------------------------------------------- css
const banner = `/* ERA design tokens. Generated by tokens/build.mjs from the ERA Figma
 * library. Do not edit by hand: re-export from Figma and run \`npm run tokens\`.
 *
 * Layers:
 *   :root                raw primitives, shared by every brand and mode
 *   [data-brand]         brand layer, re-points primitives per brand
 *   [data-theme]         semantic layer, re-points the brand layer per mode
 *
 * Components read the semantic layer only.
 */\n`;

const css = [
  banner,
  ':root {',
  ...primCss,
  '}\n',
  ...BRANDS.flatMap((b, i) => [`[data-brand='${b}'] {`, ...brandCss[i], '}\n']),
  ...MODES.flatMap((m, i) => [`[data-theme='${m}'] {`, ...semCss[i], '}\n']),
].join('\n');
writeFileSync(join(OUT, 'era.css'), css);

// ---------------------------------------------------------------------- json
const W3C_TYPE = { C: 'color', F: 'dimension', S: 'fontFamily' };
const jsonRef = (raw) => {
  const m = /^@?([PBS]):(.+)$/.exec(raw);
  if (!m) return null;
  const group = { P: 'primitives', B: 'brand', S: 'semantics' }[m[1]];
  return `{${group}.${m[2].replace(/-/g, '.')}}`;
};
const jsonValue = (name, type, raw) =>
  jsonRef(raw) ?? (type === 'F' ? (isUnitless(name) ? Number(raw) : `${raw}px`) : raw);

const nest = (root, path, leaf) => {
  let node = root;
  for (const k of path.slice(0, -1)) node = node[k] ??= {};
  node[path[path.length - 1]] = leaf;
};

const tokens = { primitives: {}, brand: {}, semantics: {} };
for (const [n, t, v] of primitives)
  nest(tokens.primitives, n.split('-'), { $type: W3C_TYPE[t], $value: jsonValue(n, t, v) });
for (const [n, t, ...vals] of brand)
  nest(tokens.brand, n.split('-'), {
    $type: W3C_TYPE[t],
    $value: jsonValue(n, t, vals[0]),
    $extensions: { 'dev.useblume.era': { modes: Object.fromEntries(BRANDS.map((b, i) => [b, jsonValue(n, t, vals[i])])) } },
  });
for (const [n, ...vals] of semantics)
  nest(tokens.semantics, n.split('-'), {
    $type: 'color',
    $value: jsonValue(n, 'C', vals[0]),
    $extensions: { 'dev.useblume.era': { modes: Object.fromEntries(MODES.map((m, i) => [m, jsonValue(n, 'C', vals[i])])) } },
  });
writeFileSync(join(OUT, 'tokens.json'), JSON.stringify(tokens, null, 2) + '\n');

console.log(
  `primitives ${primitives.length}  brand ${brand.length} x ${BRANDS.length} modes  semantics ${semantics.length} x ${MODES.length} modes\n` +
    `total custom properties: ${primCss.length + brandCss.flat().length + semCss.flat().length}\n` +
    `wrote generated/era.css and generated/tokens.json`
);
